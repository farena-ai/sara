// EC22: writes docs/API.md (the REST reference) from the SDK's route table
// (packages/sara-sdk/src/routes.ts). `--check` only says whether the file is up to date (exit 1 if not).
//   node scripts/api-reference.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTES, type Route } from '../packages/sara-sdk/src/routes.ts';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const OUT = join(ROOT, 'docs', 'API.md');

const AUTH: Record<Route['auth'], string> = {
  none: 'none',
  device: 'device token (`Authorization: Bearer <token>` from the device-code sign-in)',
  'api-key': 'API key (`Authorization: Bearer <key>`, Settings → Connections → Other apps)',
  owner: 'owner (the web app)',
};

export function render(): string {
  const lines = [
    '# Sara HTTP API reference',
    '',
    '<!-- Generated by scripts/api-reference.ts from packages/sara-sdk/src/routes.ts. Do not edit by hand. -->',
    '',
    'The routes an app or script uses to talk to Sara. The TypeScript client in',
    '[`packages/sara-sdk`](../packages/sara-sdk/README.md) wraps every one of them; a test calls each',
    'route on a throwaway server, so this list matches what Sara serves.',
    '',
    '- **Sign-in:** apps sign in with a device code (`/api/device/*`); the person approves the code in',
    '  Sara. Scripts that only need the OpenAI-compatible `/v1` use an API key instead.',
    '- **Errors:** `/api` answers `{ "error": "<plain words>" }` with the HTTP status; `/v1` answers',
    '  OpenAI\'s shape `{ "error": { "message", "type", "code" } }`.',
    '- **Approvals:** a reply can stop at an approval card (`approval` event). Answer it with',
    '  `POST /api/approvals/:id`; until then the reply waits. Her own approval rules and the admin\'s',
    '  policy always apply.',
    '- **Webhooks out:** Sara signs deliveries the Standard Webhooks way (`webhook-id`,',
    '  `webhook-timestamp`, `webhook-signature: v1,<base64>`); `verifyWebhook` in the SDK checks them.',
    '',
    '| Method and path | Auth | SDK |',
    '| --- | --- | --- |',
    ...ROUTES.map((r) => `| \`${r.method} ${r.path}\` | ${r.auth} | \`${r.sdk}\` |`),
    '',
  ];
  for (const r of ROUTES) {
    lines.push(`## ${r.method} ${r.path}`, '', r.summary, '', `- Auth: ${AUTH[r.auth]}`);
    if (r.body) lines.push(`- Body: \`${r.body}\``);
    lines.push(`- Returns: \`${r.returns}\``, `- SDK: \`sara.${r.sdk}\``, '');
  }
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(OUT, 'utf8');
    } catch {
      /* missing */
    }
    if (have !== want) {
      console.log('docs/API.md is out of date: run node scripts/api-reference.ts');
      process.exit(1);
    }
    console.log('docs/API.md is up to date.');
  } else {
    writeFileSync(OUT, want);
    console.log(`Wrote docs/API.md (${ROUTES.length} routes).`);
  }
}
